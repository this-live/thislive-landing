#!/usr/bin/env node
// Deterministic, dependency-free renderer for CHANGELOG.md.
//
// Why this exists: every PR used to hand-insert its entry at the top of
// CHANGELOG.md. Two PRs open at once both edited the same top-of-file
// location, so every merge re-conflicted every other open PR (see U73,
// 2026-09-12). The fix: each change gets its own fragment file under
// changelog.d/, and this script assembles CHANGELOG.md from all of them
// plus the frozen CHANGELOG.history.md. Adding a fragment is a new file
// (git never conflicts on two branches adding different new files), and
// CHANGELOG.md itself carries a `merge=union` .gitattributes entry as a
// second line of defense so even a raw, unassembled concurrent edit unions
// cleanly instead of conflicting.
//
// Usage: node scripts/changelog-assemble.mjs [--check]
//   --check   exit 1 if CHANGELOG.md is not already up to date (CI use);
//             otherwise (default) writes CHANGELOG.md in place.
//
// Idempotent: running this twice in a row with no fragment changes produces
// a byte-identical CHANGELOG.md both times.

import { readdirSync, readFileSync, writeFileSync, existsSync } from 'node:fs';
import { fileURLToPath } from 'node:url';
import { dirname, join } from 'node:path';

const __dirname = dirname(fileURLToPath(import.meta.url));
const ROOT = join(__dirname, '..');
const FRAGMENTS_DIR = join(ROOT, 'changelog.d');
const OUT_FILE = join(ROOT, 'CHANGELOG.md');
const HISTORY_FILE = join(ROOT, 'CHANGELOG.history.md');

const FRAGMENT_RE = /^(\d{4}-\d{2}-\d{2})-([a-z0-9][a-z0-9-]*)\.md$/;

const HEADER = `# Changelog

Project: This.Live
Purpose: Parent business/project umbrella covering company operations, GTM, pitch, and brand surfaces.

This file is generated by \`node scripts/changelog-assemble.mjs\` from the per-change
fragments in \`changelog.d/\` plus the frozen \`CHANGELOG.history.md\`. Do not hand-edit
the entries below — add a new fragment instead (see README.md, "How to add a
changelog entry"), then re-run the assembler. Running it twice with no fragment
changes produces byte-identical output.
`;

function listFragments() {
  if (!existsSync(FRAGMENTS_DIR)) return [];
  const names = readdirSync(FRAGMENTS_DIR).filter((n) => n.endsWith('.md'));
  const parsed = [];
  for (const name of names) {
    const m = FRAGMENT_RE.exec(name);
    if (!m) {
      throw new Error(
        `changelog-assemble: fragment "${name}" does not match "<YYYY-MM-DD>-<slug>.md" — rename it.`
      );
    }
    const [, date, slug] = m;
    const body = readFileSync(join(FRAGMENTS_DIR, name), 'utf8').replace(/\s+$/u, '');
    parsed.push({ name, date, slug, body });
  }
  // Deterministic order: newest date first, then slug ascending within a date.
  // This does not need to be conflict-proof on its own — merge=union on
  // CHANGELOG.md (see .gitattributes) is what makes concurrent additions
  // merge cleanly; this ordering is just for a readable rendered file.
  parsed.sort((a, b) => (a.date < b.date ? 1 : a.date > b.date ? -1 : a.slug < b.slug ? -1 : a.slug > b.slug ? 1 : 0));
  return parsed;
}

function render() {
  const fragments = listFragments();
  const blocks = fragments.map((f) => f.body.trimEnd());
  const parts = [HEADER.trimEnd(), ''];
  if (blocks.length > 0) {
    parts.push(blocks.join('\n\n'), '');
  }
  parts.push(
    '---',
    '',
    `Entries before the fragment system (pre-2026-09-12, U73): see [CHANGELOG.history.md](${'CHANGELOG.history.md'}).`,
    ''
  );
  return parts.join('\n');
}

function main() {
  const check = process.argv.includes('--check');
  if (!existsSync(HISTORY_FILE)) {
    console.error(`changelog-assemble: missing ${HISTORY_FILE}`);
    process.exit(1);
  }
  const rendered = render();
  if (check) {
    const current = existsSync(OUT_FILE) ? readFileSync(OUT_FILE, 'utf8') : '';
    if (current !== rendered) {
      console.error('changelog-assemble --check: CHANGELOG.md is stale. Run `node scripts/changelog-assemble.mjs`.');
      process.exit(1);
    }
    console.log('changelog-assemble --check: CHANGELOG.md is up to date.');
    return;
  }
  writeFileSync(OUT_FILE, rendered, 'utf8');
  console.log(`changelog-assemble: wrote ${OUT_FILE} from ${listFragments().length} fragment(s).`);
}

main();
